package io.github.kazox61.spacetimedb.codegen

import io.github.kazox61.spacetimedb.codegen.emit.GeneratorInfo
import io.github.kazox61.spacetimedb.codegen.emit.KotlinEmitter
import io.github.kazox61.spacetimedb.codegen.model.Normalizer
import io.github.kazox61.spacetimedb.codegen.schema.SchemaJson
import java.io.File

/** Generates Kotlin client bindings: the entry point for the CLI and the Gradle plugin. */
public object Bindings {
    private const val GENERATED_PREFIX = "// THIS FILE IS AUTOMATICALLY GENERATED BY SPACETIMEDB"
    /** This generator's version, from the jar manifest. */
    public val generatorVersion: String = Bindings::class.java.`package`?.implementationVersion ?: "dev"

    /**
     * Bindings for a schema (RawModuleDef V10 JSON, as `extract-schema` prints it): file path to content.
     * [spacetimeVersion] is the SpacetimeDB version the schema came from; it ends up in
     * `RemoteModule.cliVersion`, which the SDK checks against its minimum.
     */
    public fun generate(schemaJson: String, spacetimeVersion: String): Map<String, String> = KotlinEmitter.generate(
        Normalizer.normalize(SchemaJson.parse(schemaJson)),
        GeneratorInfo(
            versionComment = "// This was generated using spacetimedb-kotlin codegen $generatorVersion " +
                "from a SpacetimeDB $spacetimeVersion schema.",
            cliVersion = spacetimeVersion,
        ),
    )

    /** Builds the module, extracts its schema and generates its bindings. */
    public fun generateFromModule(moduleDir: File, tools: SpacetimeTools, build: Boolean = true): Map<String, String> {
        if (build) tools.build(moduleDir)
        val schema = tools.extractSchema(SpacetimeTools.artifact(moduleDir))
        return generate(schema, tools.version())
    }

    /**
     * Replaces the contents of [outDir] with [files]. Refuses if [outDir] holds anything that isn't
     * generated bindings, so a misconfigured path can't wipe hand-written code.
     */
    public fun write(files: Map<String, String>, outDir: File) {
        val foreign = outDir.walkTopDown().filter { it.isFile }.firstOrNull { file ->
            file.extension != "kt" || !file.useLines { lines -> lines.firstOrNull()?.startsWith(GENERATED_PREFIX) == true }
        }
        if (foreign != null) {
            throw SpacetimeToolException("Not replacing $outDir: $foreign is not a generated binding file. Use a folder of its own for the bindings.")
        }
        outDir.deleteRecursively()
        for ((path, content) in files) {
            val file = outDir.resolve(path)
            file.parentFile.mkdirs()
            file.writeText(content)
        }
    }
}
